#!/usr/bin/env python3
"""Wally's Journey: catch-rate audit (separate from encounter rarity).

For every species that can appear in the wild on an Emerald map (normal slots or
rare visitors) this prints its effective catch rate, its rarest encounter chance
and the chance to catch it with a single Poke Ball (the only ball in the game):
  * fresh:   full HP, no status
  * worn:    1 HP and asleep (the best a player can do)
Effective rate = canon rate, except legendary/mythical species, which the game
caps at 3 (see WallyJourney_AdjustCatchRate in src/wally_journey.c).

Capture math mirrors ComputeCaptureOdds/ComputeBallShakeOdds in
src/battle_script_commands.c (Gen 6+ formula, integer truncation, 4 shake checks,
critical captures ignored). Per-ball chance is ~odds/255.

Run: python3 tools/audit_wally_catch_rates.py [--markdown docs/WALLY_CATCH_RATE_LEDGER.md]
"""
import argparse
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FAM = ROOT / "src/data/pokemon/species_info"
ENTRY = re.compile(r"\[\s*(SPECIES_[A-Z0-9_]+)\s*\]\s*=\s*\n?\s*\{")


def species_table():
    out = {}
    for g in range(1, 10):
        text = (FAM / f"gen_{g}_families.h").read_text(encoding="utf-8")
        starts = list(ENTRY.finditer(text))
        for i, m in enumerate(starts):
            body = text[m.end(): starts[i + 1].start() if i + 1 < len(starts) else len(text)]
            c = re.search(r"\.catchRate\s*=\s*(\d+)", body)
            legend = bool(re.search(r"\.is(Mythical|SubLegendary|RestrictedLegendary)\s*=\s*TRUE", body))
            if c:
                out[m.group(1)] = (int(c.group(1)), legend)
    return out


def wild_chances():
    """species -> (best-case rarest chance %, map) across Emerald maps."""
    j = json.loads((ROOT / "src/data/wild_encounters.json").read_text(encoding="utf-8"))
    group = next(g for g in j["wild_encounter_groups"] if g["label"] == "gWildMonHeaders")
    rates = {}
    for f in group["fields"]:
        rates[f["type"]] = f["encounter_rates"]
    maps = {json.loads(p.read_text())["id"] for p in (ROOT / "data/maps").glob("*/map.json")
            if not p.parent.name.endswith("_Frlg")}
    best = {}
    for e in group["encounters"]:
        if e.get("map") not in maps:
            continue
        for k, v in e.items():
            if not isinstance(v, dict) or not isinstance(v.get("mons"), list):
                continue
            key = k if k in rates else k.split("_")[0] + "_mons"
            r = rates.get(k) or rates.get(key)
            if not r:
                continue
            per = {}
            for i, mon in enumerate(v["mons"]):
                if i < len(r):
                    per[mon["species"]] = per.get(mon["species"], 0) + r[i]
            for sp, pct in per.items():
                if sp not in best or pct > best[sp][0]:
                    best[sp] = (pct, e["map"])
    vis = (ROOT / "src/data/wally_rare_visitors.h").read_text(encoding="utf-8")
    for mp, sp, odds in re.findall(r"VISITOR\(\s*(MAP_\w+)\s*,\s*WILD_AREA_\w+\s*,\s*(SPECIES_\w+)\s*,\s*(\d+)", vis):
        pct = int(odds) / 100
        if sp not in best or pct > best[sp][0]:
            best[sp] = (pct, mp + " (visitor)")
    return best


def per_ball(rate, worn):
    m = 300  # max HP; result is insensitive to it
    hp = 1 if worn else m
    odds = (m * 3 - hp * 2) * rate // (m * 3)
    if worn:
        odds = odds * 25 // 10
    if odds >= 255:
        return 1.0
    if odds <= 0:
        return 0.0
    b = 1048560 // int(math.isqrt(math.isqrt(16711680 // odds)) or 1)
    b = min(b, 65536)
    return (b / 65536) ** 4


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--markdown")
    a = ap.parse_args()
    sp = species_table()
    wild = wild_chances()
    rows = []
    for s, (pct, where) in sorted(wild.items()):
        if s not in sp:
            continue
        canon, legend = sp[s]
        eff = min(canon, 3) if legend else canon
        rows.append((s, canon, eff, pct, where, per_ball(eff, False), per_ball(eff, True), legend))
    flags = [r for r in rows if r[3] <= 5 and r[1] >= 190]
    hard_common = [r for r in rows if r[3] >= 20 and r[1] <= 45]
    print(f"Wild species audited: {len(rows)}")
    print(f"Rare (<=5%) but very easy to catch (canon rate >= 190): {len(flags)}")
    for r in flags:
        print(f"  {r[0]}: rate {r[1]}, rarest-best {r[3]}% at {r[4]}")
    print(f"Common (>=20%) but hard (rate <= 45): {len(hard_common)}")
    for r in hard_common:
        print(f"  {r[0]}: rate {r[1]}, {r[3]}% at {r[4]}")
    if a.markdown:
        lines = ["# Catch-rate ledger (generated)", "",
                 "Generated by `tools/audit_wally_catch_rates.py`. Rates are canon (Gen 9 data from pokeemerald-expansion) "
                 "except legendary/mythical species, which the game caps at 3. Per-ball chances use the in-game Gen 6+ "
                 "formula with a Poké Ball, ignoring critical captures. Encounter % is the best single-method chance on any "
                 "Emerald map (rare visitors included). Static legendary/mythical encounters are listed in the requirements ledger.", "",
                 "| Species | Canon rate | Game rate | Best encounter % | Where | Catch/ball fresh | Catch/ball 1 HP + asleep |",
                 "|---|---|---|---|---|---|---|"]
        for r in rows:
            lines.append(f"| {r[0][8:]} | {r[1]} | {r[2]} | {r[3]:g} | {r[4][4:]} | {r[5]*100:.1f}% | {r[6]*100:.1f}% |")
        Path(a.markdown).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote", a.markdown)


if __name__ == "__main__":
    main()

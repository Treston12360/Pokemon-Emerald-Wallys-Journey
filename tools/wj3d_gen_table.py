#!/usr/bin/env python3
"""Regenerate src/data/wj3d_backdrops.h from graphics/battle_environment/wj3d/<map>/.
Folder names are map names in lower case without "MAP_" (route104 -> MAP_ROUTE104,
petalburg_city -> MAP_PETALBURG_CITY). The INCGFX lines must be literal: the build's
scaninc/preproc read them before the C preprocessor runs."""
import os
ROOT = os.path.join(os.path.dirname(__file__), '..')
base = os.path.join(ROOT, 'graphics/battle_environment/wj3d')
dirs = sorted(d for d in os.listdir(base) if os.path.exists(os.path.join(base, d, 'tiles.png')))
out = ['// Wally\'s Journey: 3D battle backdrops (generated by tools/wj3d_gen_table.py; graphics made by',
       '// tools/wj3d_backdrop.py from Emerald 3DS captures; Emerald 3DS by Zallax and contributors).', '']
for d in dirs:
    n = ''.join(p.capitalize() for p in d.split('_'))
    g = f'graphics/battle_environment/wj3d/{d}'
    out.append(f'static const u32 sWJ3D_{n}_Tiles[] = INCGFX_U32("{g}/tiles.png", ".4bpp.smol");')
    out.append(f'static const u32 sWJ3D_{n}_Map[] = INCGFX_U32("{g}/tilemap.bin", ".smolTM");')
    out.append(f'static const u16 sWJ3D_{n}_Pal[] = INCGFX_U16("{g}/palette.pal", ".gbapal");')
out += ['', 'static const struct WJ3DBackdrop sWJ3DBackdrops[] =', '{']
for d in dirs:
    n = ''.join(p.capitalize() for p in d.split('_'))
    m = 'MAP_' + d.upper()
    out.append(f'    {{MAP_GROUP({m}), MAP_NUM({m}), sWJ3D_{n}_Tiles, sWJ3D_{n}_Map, sWJ3D_{n}_Pal}},')
out += ['};', '']
open(os.path.join(ROOT, 'src/data/wj3d_backdrops.h'), 'w').write('\n'.join(out))
print('backdrops:', ', '.join(dirs))

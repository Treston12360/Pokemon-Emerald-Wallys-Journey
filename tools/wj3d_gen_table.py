#!/usr/bin/env python3
"""Regenerate src/data/wj3d_backdrops.h from graphics/battle_environment/wj3d/<folder>/.

Folder names are map names in lower case without "MAP_" (route104 -> MAP_ROUTE104,
petalburg_city -> MAP_PETALBURG_CITY). A folder ending in "__water" (route104__water) is that
map's backdrop for surfing battles (WATER or POND); a plain folder is used for every other
(land / cave / building) battle on the map. An optional environment.txt in a folder (e.g.
BATTLE_ENVIRONMENT_SAND) limits a plain backdrop to battles in that one environment.

The INCGFX lines must be literal: the build's scaninc/preproc read them before the C
preprocessor runs.
"""
import os

ROOT = os.path.join(os.path.dirname(__file__), '..')
base = os.path.join(ROOT, 'graphics/battle_environment/wj3d')
dirs = sorted(d for d in os.listdir(base) if os.path.exists(os.path.join(base, d, 'tiles.png')))


def ident(folder):
    return ''.join(p.capitalize() for p in folder.replace('__', '_').split('_'))


def row(folder):
    mapname, _, kind = folder.partition('__')
    m = 'MAP_' + mapname.upper()
    if kind == 'water':
        env = 'WJ3D_WATER_ENVIRONMENTS'
    else:
        envf = os.path.join(base, folder, 'environment.txt')
        env = open(envf).read().strip() if os.path.exists(envf) else 'WJ3D_ANY_ENVIRONMENT'
    n = ident(folder)
    return f'    {{MAP_GROUP({m}), MAP_NUM({m}), sWJ3D_{n}_Tiles, sWJ3D_{n}_Map, sWJ3D_{n}_Pal, {env}}},'


out = ['// Wally\'s Journey: 3D battle backdrops (generated by tools/wj3d_gen_table.py; graphics made by',
       '// tools/wj3d_backdrop.py from Emerald 3DS captures; Emerald 3DS by Zallax and contributors).', '']
for d in dirs:
    n = ident(d)
    g = f'graphics/battle_environment/wj3d/{d}'
    out.append(f'static const u32 sWJ3D_{n}_Tiles[] = INCGFX_U32("{g}/tiles.png", ".4bpp.smol");')
    out.append(f'static const u32 sWJ3D_{n}_Map[] = INCGFX_U32("{g}/tilemap.bin", ".smolTM");')
    out.append(f'static const u16 sWJ3D_{n}_Pal[] = INCGFX_U16("{g}/palette.pal", ".gbapal");')
out += ['', 'static const struct WJ3DBackdrop sWJ3DBackdrops[] =', '{']
out += [row(d) for d in dirs]
out += ['};', '']
open(os.path.join(ROOT, 'src/data/wj3d_backdrops.h'), 'w').write('\n'.join(out))
print(len(dirs), 'backdrops')

#!/usr/bin/env python3
"""Wally's Journey: list the outdoor townspeople who may go home at night or
shelter from rain (src/data/wally_ambient_npcs.h).

An NPC qualifies only if it is pure flavour: outdoors (town, city, route),
not a trainer, an ordinary person sprite, and its script does nothing but
show text (msgbox MSGBOX_NPC, optionally behind goto_if checks that also only
show text). NPCs moved or referenced by any script, story characters, item
givers and anything with a flag-driven role are left out, so hiding them can
never block progress.

Run: python3 tools/gen_wally_ambient_npcs.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src/data/wally_ambient_npcs.h"
OUTDOOR = {"MAP_TYPE_TOWN", "MAP_TYPE_CITY", "MAP_TYPE_ROUTE", "MAP_TYPE_OCEAN_ROUTE"}
STORY_GFX = re.compile(r"WALLY|STEVEN|BRENDAN|MAY|BIRCH|NORMAN|MOM|ARCHIE|MAXIE|SHELLY|MATT|TABITHA|COURTNEY|"
                       r"WALLACE|JUAN|SCOTT|STERN|COZMO|BRINEY|DEVON|GRUNT|AQUA|MAGMA|RIVAL|LEADER|ELITE|"
                       r"ITEM_BALL|CUTTABLE|BREAKABLE|PUSHABLE|BERRY|TRUCK|SS_TIDAL|SUBMARINE|BIRTH|LIGHT|"
                       r"KECLEON|SUDOWOODO|VOLTORB|KYOGRE|GROUDON|RAYQUAZA|REGI|LATI|DEOXYS|MEW|HO_OH|LUGIA|"
                       r"SPECIES|VAR_|FOSSIL|BALL|STATUE|SIGN|DOLL|CUSHION|BOAT|CABLE|MANIAC|SAILOR_.*BOAT|TWIN|"
                       r"ANABEL|GABBY|TY\b|PICNICKER_STATIC|PSYCHIC_M_STATIC|LINK|ARTIST|REPORTER|NURSE|CLERK")
SIMPLE_LINE = re.compile(r"^\s*(special WallyJourney_GetSeasonForScript|msgbox \w+, MSGBOX_NPC|goto_if_(set|unset) FLAG_\w+, \w+|goto_if_(ge|eq|le|lt|gt|ne) VAR_\w+, \w+, \w+|end)\s*$")


def labels(text):
    out = {}
    cur = None
    for line in text.splitlines():
        m = re.match(r"^(\w+)::?\s*$", line)
        if m:
            cur = m.group(1)
            out[cur] = []
            continue
        if cur and line.strip() and not line.strip().startswith("@"):
            out[cur].append(line)
    return out


def is_simple(name, body_of, depth=0):
    body = body_of.get(name)
    if body is None or depth > 4:
        return False
    for line in body:
        if line.strip() == "end":
            return True
        if not SIMPLE_LINE.match(line):
            return False
        g = re.search(r", (\w+)\s*$", line)
        if line.strip().startswith("goto_if") and not is_simple(g.group(1), body_of, depth + 1):
            return False
    return False


def main():
    all_scripts = "\n".join(p.read_text(errors="replace") for p in (ROOT / "data").rglob("*.inc"))
    body_of = labels(all_scripts)
    picks = []
    for mj in sorted((ROOT / "data/maps").glob("*/map.json")):
        if mj.parent.name.endswith("_Frlg"):
            continue
        j = json.loads(mj.read_text())
        if j.get("map_type") not in OUTDOOR:
            continue
        map_scripts = (mj.parent / "scripts.inc").read_text(errors="replace") if (mj.parent / "scripts.inc").exists() else ""
        for obj in j.get("object_events", []):
            if obj.get("type", "object") != "object":
                continue
            script = obj.get("script", "0")
            if obj.get("trainer_type", "TRAINER_TYPE_NONE") != "TRAINER_TYPE_NONE" or script in ("0", "NULL"):
                continue
            if STORY_GFX.search(obj.get("graphics_id", "")):
                continue
            if obj.get("flag", "0") not in ("0", ""):
                continue
            lid = obj.get("local_id")
            if lid and re.search(rf"\b{re.escape(lid)}\b", map_scripts):
                continue
            if not is_simple(script, body_of):
                continue
            picks.append(script)
    picks = sorted(set(picks))
    lines = ["// Generated by tools/gen_wally_ambient_npcs.py - do not edit by hand.",
             "// Outdoor flavour NPCs that may go home at night or shelter from rain.", ""]
    lines += [f"extern const u8 {s}[];" for s in picks]
    lines += ["", "static const u8 *const sWallyAmbientNpcScripts[] =", "{"]
    lines += [f"    {s}," for s in picks]
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(picks)} ambient NPCs -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

#!/bin/bash
# Lists every function the asm effect_ptr macro marked as calling
# Script_RequestEffects (read from the ELF data objects' wj_effect_funcs
# section) and writes them as a C table for the PC build.
# usage: effect_funcs.sh OUT.c OBJ...
out=$1; shift
names=$(for f in "$@"; do objdump -r -j wj_effect_funcs "$f" 2>/dev/null; done | awk '$2 == "R_386_32" {print $3}' | sort -u)
{
  echo "// Generated by tools/pc/effect_funcs.sh. Do not edit."
  for n in $names; do echo "extern char $n[];"; done
  echo "const void *const gWjEffectFuncs[] = {"
  for n in $names; do echo "    $n,"; done
  echo "};"
  echo "const unsigned int gWjEffectFuncsCount = sizeof(gWjEffectFuncs) / sizeof(gWjEffectFuncs[0]);"
} > "$out"
test $(echo "$names" | wc -w) -gt 0

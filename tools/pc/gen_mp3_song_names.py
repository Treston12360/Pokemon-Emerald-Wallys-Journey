#!/usr/bin/env python3
"""ENG-MP3: write src/platform/mp3_song_names.h = song number -> "MUS_NAME" (from include/constants/songs.h).
Only MUS_ songs (background music) can be replaced by an MP3. Run by Makefile.pc when songs.h changes."""
import re, sys
names = {}
for ln in open('include/constants/songs.h'):
    m = re.match(r'#define (MUS_\w+)\s+(\d+)\b', ln)
    if m and m.group(1) not in ('MUS_DUMMY',):
        names.setdefault(int(m.group(2)), m.group(1))
out = ['// Generated by tools/pc/gen_mp3_song_names.py from include/constants/songs.h - do not edit.',
       'static const char *const sMp3SongNames[] = {']
out += ['    [%d] = "%s",' % (n, s) for n, s in sorted(names.items())]
out += ['};', '']
open(sys.argv[1] if len(sys.argv) > 1 else 'src/platform/mp3_song_names.h', 'w').write('\n'.join(out))

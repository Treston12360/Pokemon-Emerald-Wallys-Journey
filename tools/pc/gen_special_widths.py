#!/usr/bin/env python3
"""PC port: the specials (data/specials.inc) that return an 8-bit value (bool8, u8, s8), as a C table.

`specialvar VAR, Special` calls every special through a u16-returning pointer (scrcmd.c gSpecials). On the GBA (ARM)
an 8-bit return is always widened to 32 bits; on x86 only the low 8 bits (AL) are set and the rest of the register is
whatever was there - so a bool8 special could give the script 0x2301 for TRUE, and `goto_if_eq VAR_RESULT, TRUE` fails
(found 2026-11-28: ShouldTryRematchBattle - Match Call rematches by talking never started). scrcmd.c keeps only the low
8 bits for the specials listed here (and sign-extends the s8 ones).

python3 gen_special_widths.py OUT.c   (run by Makefile.pc on every build: reads data/specials.inc and src/**/*.c)
"""
import glob, re, sys

names = set(re.findall(r'^\s*def_special\s+(\w+)', open('data/specials.inc').read(), re.M))
proto = re.compile(r'^[ \t]*(?:static[ \t]+)?(?:inline[ \t]+)?(bool8|u8|s8)[ \t]+\**[ \t]*(\w+)[ \t]*\([ \t]*void[ \t]*\)[ \t]*$', re.M)
narrow = {}
for f in sorted(glob.glob('src/**/*.c', recursive=True)):
    if '/platform/server/' in f:
        continue
    for typ, name in proto.findall(open(f, errors='ignore').read()):
        if name in names:
            narrow[name] = typ

out = ['/* Generated by tools/pc/gen_special_widths.py from data/specials.inc - do not edit. */',
       '/* (no game headers here: each special is declared only by name, its address taken) */']
for n in sorted(narrow):
    out.append('extern void %s(void);' % n)
out.append('const void *const gPcNarrowSpecials[] = {')
out += ['    (const void *)%s,' % n for n in sorted(narrow) if narrow[n] != 's8']
out.append('};')
out.append('const unsigned int gPcNarrowSpecialsCount = sizeof(gPcNarrowSpecials) / sizeof(gPcNarrowSpecials[0]);')
out.append('const void *const gPcSignedNarrowSpecials[] = {')
out += ['    (const void *)%s,' % n for n in sorted(narrow) if narrow[n] == 's8']
out.append('    (const void *)0,')
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')

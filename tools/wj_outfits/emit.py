#!/usr/bin/env python3
"""Write Wally's Journey outfit assets + C data into the repo (run after gen.py logic)."""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import gen
from PIL import Image
G=gen.G; R=gen.R
OW=G+'graphics/object_events/pics/people/wj_outfits/'
TR=G+'graphics/trainers/wj_outfits/'
os.makedirs(OW,exist_ok=True); os.makedirs(TR,exist_ok=True)
DISPLAY={'brendan':'BRENDAN','may':'MAY','red':'RED','leaf':'LEAF','ethan':'ETHAN','lyra':'LYRA','lucas':'LUCAS','dawn':'DAWN',
 'hilbert':'HILBERT','hilda':'HILDA','nate':'NATE','rosa':'ROSA','calem':'CALEM','serena':'SERENA','elio':'ELIO','selene':'SELENE',
 'victor':'VICTOR','gloria':'GLORIA','florian':'FLORIAN','juliana':'JULIANA'}
def cname(n): return n.capitalize()
def rgb555(c): return (c[0]>>3)|((c[1]>>3)<<5)|((c[2]>>3)<<10)
def layerid(c): return {(255,0,0):1,(0,255,0):2,(0,0,255):3}.get(tuple(c),0)
def remap_to(im,pal):
    ip=[tuple(im.getpalette()[i*3:i*3+3]) for i in range(16)]
    rm=[0]+[min(range(1,16),key=lambda j:sum((a-b)**2 for a,b in zip(ip[i],pal[j]))) for i in range(1,16)]
    out=im.point(lambda v:rm[v] if v<16 else 0); out.putpalette([v for c in pal for v in c]); return out
# 1. sheets
for n,g in gen.OUTFITS:
    gen.OUT=OW; gen.build(n,g)
    d=OW+n+'/'
    w=Image.open(d+'walking.png'); r=Image.open(d+'running.png')
    nr=Image.new('P',(288,32),0); nr.putpalette(w.getpalette()); nr.paste(w,(0,0)); nr.paste(r,(144,0)); nr.save(d+'normal.png')
    for f in ('walking.png','running.png','ow.pal','ow_layers.pal'):
        if os.path.exists(d+f): os.remove(d+f)
# 1b. owner-approved hand-made sheets (hilbert.py/hsurf.py/hbike.py/hprop.py output)
import shutil
HB=os.path.dirname(os.path.abspath(__file__))+'/hb/'
for st in ('surfing','mach_bike','acro_bike','fishing','field_move','watering','decorating'):
    shutil.copy(HB+st+'_B.png', OW+'hilbert/'+st+'.png')
w=Image.open(gen.R+'graphics/object_events/pics/people/hilbert/walking.png'); r=Image.open(HB+'running_B.png')
nr=Image.new('P',(288,32),0); nr.putpalette(w.getpalette()); nr.paste(w,(0,0)); nr.paste(r,(144,0)); nr.save(OW+'hilbert/normal.png')
for n in ('red','leaf'):
    for st in ('watering','decorating'):
        shutil.copy(os.path.dirname(os.path.abspath(__file__))+'/%s/%s.png'%(n,st), OW+n+'/'+st+'.png')
# 2. trainer pics + palettes
meta=[]
for n,g in gen.OUTFITS:
    pd=R+'graphics/rogue_palettes/%s/'%gen.PALDIR.get(n,n)
    owb=gen.readpal(pd+'object_event_base.pal'); owl=gen.readpal(pd+'object_event_layers.pal')
    if os.path.exists(pd+'trainer_frontback_base.pal'):
        fb=gen.readpal(pd+'trainer_frontback_base.pal'); fl=gen.readpal(pd+'trainer_frontback_layers.pal'); bb,bl=fb,fl
    else:
        fb=gen.readpal(pd+'trainer_front_base.pal'); fl=gen.readpal(pd+'trainer_front_layers.pal')
        bb=bl=None
        if os.path.exists(pd+'trainer_back_base.pal'):
            bb=gen.readpal(pd+'trainer_back_base.pal'); bl=gen.readpal(pd+'trainer_back_layers.pal')
    front=Image.open(R+'graphics/trainers/front_pics/%s_front_pic.png'%n)
    remap_to(front,fb).save(TR+n+'_front.png')
    bp=R+'graphics/trainers/back_pics/%s_back_pic.png'%n
    backframes=0
    if os.path.exists(bp) and bb:
        b=Image.open(bp); remap_to(b,bb).save(TR+n+'_back.png'); backframes=b.height//64
    meta.append(dict(n=n,g=g,owb=owb,owl=owl,fb=fb,fl=fl,bb=bb if backframes else None,bl=bl if backframes else None,backframes=backframes))
# 3. object event C data (included inside event_object_movement.c)
pt=open(G+'src/data/object_events/object_event_pic_tables.h').read()
gi=open(G+'src/data/object_events/object_event_graphics_info.h').read()
STATES=[('Normal','normal',2,4),('MachBike','mach_bike',4,4),('AcroBike','acro_bike',4,4),('Surfing','surfing',4,4),
        ('FieldMove','field_move',4,4),('Fishing','fishing',4,4),('Watering','watering',4,4),('Decorating','decorating',0,0)]
o=['// Generated by scratchpad outfit/emit.py - Wally\'s Journey player outfits (sprites from Emerald Rogue by Pokabbie and its artists).','']
for m in meta:
    C=cname(m['n']); T='Brendan' if m['g']=='M' else 'May'
    for st,f,mw,mh in STATES:
        path='graphics/object_events/pics/people/wj_outfits/%s/%s.png'%(m['n'],f if f!='normal' else 'normal')
        if mw: o.append('static const u32 sWJPic_%s%s[] = INCGFX_U32("%s", ".4bpp", "-mwidth %d -mheight %d");'%(C,st,path,mw,mh))
        else: o.append('static const u32 sWJPic_%s%s[] = INCGFX_U32("%s", ".4bpp");'%(C,st,path))
    for st,f,mw,mh in STATES:
        tbl=re.search(r'static const struct SpriteFrameImage sPicTable_%s%s\[\] = \{(.*?)\};'%(T,st),pt,re.S).group(1)
        tbl=re.sub(r'gObjectEventPic_\w+','sWJPic_%s%s'%(C,st),tbl)
        o.append('static const struct SpriteFrameImage sWJPicTable_%s%s[] = {%s};'%(C,st,tbl))
        info=re.search(r'const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_%s%s = \{(.*?)\n\};'%(T,st),gi,re.S).group(1)
        info=re.sub(r'\.paletteTag = \w+','.paletteTag = OBJ_EVENT_PAL_TAG_WJ_PLAYER',info)
        info=re.sub(r'\.images = \w+','.images = sWJPicTable_%s%s'%(C,st),info)
        o.append('static const struct ObjectEventGraphicsInfo sWJGfxInfo_%s%s = {%s\n};'%(C,st,info))
    o.append('')
o.append('static const struct ObjectEventGraphicsInfo *const sWJOutfitGfxInfos[WJ_OUTFIT_COUNT][WJ_OUTFIT_GFX_COUNT] = {')
for m in meta:
    C=cname(m['n'])
    o.append('    [WJ_OUTFIT_%s] = {%s},'%(m['n'].upper(),', '.join('&sWJGfxInfo_%s%s'%(C,st) for st,_,_,_ in STATES)))
o.append('};')
open(G+'src/data/object_events/wj_outfit_gfx.h','w').write('\n'.join(o)+'\n')
# 4. trainer pic C data (included inside src/data/graphics/trainers.h context)
o=['// Generated by scratchpad outfit/emit.py - Wally\'s Journey player outfits.','']
for m in meta:
    C=cname(m['n'])
    o.append('static const u32 sWJTrainerFront_%s[] = INCGFX_U32("graphics/trainers/wj_outfits/%s_front.png", ".4bpp.smol");'%(C,m['n']))
    if m['backframes']: o.append('static const u8 sWJTrainerBack_%s[] = INCGFX_U8("graphics/trainers/wj_outfits/%s_back.png", ".4bpp");'%(C,m['n']))
o.append('const struct TrainerFrontPicInfo gWJOutfitFrontPics[WJ_OUTFIT_COUNT] = {')
for m in meta:
    o.append('    [WJ_OUTFIT_%s] = {.imageData = sWJTrainerFront_%s, .paletteData = gWJPlayerFrontPal, .mugshotRotation = 0x200},'%(m['n'].upper(),cname(m['n'])))
o.append('};')
o.append('const struct TrainerBackPicInfo gWJOutfitBackPics[WJ_OUTFIT_COUNT] = {')
for m in meta:
    if m['backframes']==5:
        o.append('    [WJ_OUTFIT_%s] = {.coordinates = {.size = 8, .y_offset = 5}, .image = {.data = sWJTrainerBack_%s, .size = TRAINER_PIC_SIZE, .relativeFrames = TRUE}, .paletteData = gWJPlayerBackPal, .animation = sBackAnims_Kanto},'%(m['n'].upper(),cname(m['n'])))
    elif m['backframes']==4:
        o.append('    [WJ_OUTFIT_%s] = {.coordinates = {.size = 8, .y_offset = 4}, .image = {.data = sWJTrainerBack_%s, .size = TRAINER_PIC_SIZE, .relativeFrames = TRUE}, .paletteData = gWJPlayerBackPal, .animation = sBackAnims_Hoenn},'%(m['n'].upper(),cname(m['n'])))
    else:
        bk='gTrainerBackPic_Brendan' if m['g']=='M' else 'gTrainerBackPic_May'
        pl='gTrainerPalette_Brendan' if m['g']=='M' else 'gTrainerPalette_May'
        o.append('    [WJ_OUTFIT_%s] = {.coordinates = {.size = 8, .y_offset = 4}, .image = {.data = %s, .size = TRAINER_PIC_SIZE, .relativeFrames = TRUE}, .paletteData = %s, .animation = sBackAnims_Hoenn}, // no back pic: gender default'%(m['n'].upper(),bk,pl))
o.append('};')
open(G+'src/data/graphics/wj_outfit_trainers.h','w').write('\n'.join(o)+'\n')
# 5. outfit meta (names, gender, palettes, layers) for src/wj_outfit.c
def pal(p): return '{'+', '.join('0x%04X'%rgb555(c) for c in p)+'}'
def lay(l): return '{'+', '.join(str(layerid(c)) for c in l)+'}'
o=['// Generated by scratchpad outfit/emit.py - Wally\'s Journey player outfits.','']
o.append('static const struct WJOutfitInfo sWJOutfits[WJ_OUTFIT_COUNT] = {')
for m in meta:
    o.append('    [WJ_OUTFIT_%s] = {'%m['n'].upper())
    o.append('        .name = COMPOUND_STRING("%s"), .gender = %s, .hasBack = %s,'%(DISPLAY[m['n']],'MALE' if m['g']=='M' else 'FEMALE','TRUE' if m['backframes'] else 'FALSE'))
    o.append('        .owPal = %s, .owLayers = %s,'%(pal(m['owb']),lay(m['owl'])))
    o.append('        .frontPal = %s, .frontLayers = %s,'%(pal(m['fb']),lay(m['fl'])))
    if m['backframes']: o.append('        .backPal = %s, .backLayers = %s,'%(pal(m['bb']),lay(m['bl'])))
    o.append('    },')
o.append('};')
open(G+'src/data/wj_outfits.h','w').write('\n'.join(o)+'\n')
# constants
o=['#ifndef GUARD_CONSTANTS_WJ_OUTFITS_H','#define GUARD_CONSTANTS_WJ_OUTFITS_H','// Generated by scratchpad outfit/emit.py','enum WJOutfitId {']
o+=['    WJ_OUTFIT_%s,'%m['n'].upper() for m in meta]
o+=['    WJ_OUTFIT_COUNT,','};','','enum WJOutfitGfxSlot {']
o+=['    WJ_OUTFIT_GFX_%s,'%f.upper() for _,f,_,_ in STATES]
o+=['    WJ_OUTFIT_GFX_COUNT,','};','','#endif']
open(G+'include/constants/wj_outfits.h','w').write('\n'.join(o)+'\n')
print('ok', len(meta))
